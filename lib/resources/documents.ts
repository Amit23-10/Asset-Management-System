function assetEntryFields(entryType: 'opening' | 'new'): MasterField[] {
  const fields: MasterField[] = [
    { name: 'id', label: 'Asset ID', type: 'text', readOnly: true, placeholder: 'Auto', section: 'Asset' },
    { name: 'name', label: 'Asset Name', type: 'text', required: true, maxLength: 100, section: 'Asset' },
    { name: 'group', label: 'Group', type: 'select', required: true, optionsResource: 'asset-groups', section: 'Asset' },
    { name: 'subGroup', label: 'Sub Group', type: 'select', required: true, optionsResource: 'asset-sub-groups', section: 'Asset' },
    { name: 'brand', label: 'Brand', type: 'select', optionsResource: 'brands', section: 'Asset' },
    { name: 'branch', label: 'Branch', type: 'select', required: true, optionsResource: 'branches', section: 'Location' },
    { name: 'department', label: 'Department', type: 'select', optionsResource: 'departments', section: 'Location' },
    { name: 'user', label: 'Fixed Asset User', type: 'select', optionsResource: 'asset-users', section: 'Location' },
    { name: 'vendor', label: 'Supplier / Vendor', type: 'select', optionsResource: 'vendors', section: 'Location' },
    { name: 'dateOfPurchase', label: 'Date of Purchase', type: 'date', required: true, section: 'Dates & Cost' },
    { name: 'dateOfOperation', label: 'Date of Operation', type: 'date', required: true, section: 'Dates & Cost' },
    { name: 'cost', label: 'Cost', type: 'number', required: true, section: 'Dates & Cost' },
    { name: 'tax', label: 'Tax', type: 'number', section: 'Dates & Cost' },
    { name: 'vat', label: 'VAT', type: 'number', section: 'Dates & Cost' },
  ]
  if (entryType === 'opening') {
    fields.push({
      name: 'openingAccumulatedDepn',
      label: 'Opening Accumulated Depreciation',
      type: 'number',
      section: 'Dates & Cost',
    })
  }
  fields.push(
    { name: 'bookValue', label: 'Book Value', type: 'number', readOnly: true, source: 'bookValue', section: 'Dates & Cost' },
    { name: 'remarks', label: 'Remarks', type: 'textarea', maxLength: 250, section: 'Dates & Cost' },
  )
  return fields
}

